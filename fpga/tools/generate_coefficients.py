"""Generate the synthesizable 120-entry signed Q15 coefficient ROM."""
import argparse
import math
from pathlib import Path


def coefficients():
    return [(round(32767 * math.cos(2 * math.pi * n / 120)),
             round(32767 * math.sin(2 * math.pi * n / 120))) for n in range(120)]


def render():
    lines = ['`timescale 1ns/1ps', '// Generated by tools/generate_coefficients.py; Q15, period 120.',
             'module coefficient_rom(input wire [6:0] address,',
             '    output reg signed [15:0] cos_coeff, output reg signed [15:0] sin_coeff);',
             '    always @* begin', '        case(address)']
    for n, (c, s) in enumerate(coefficients()):
        lines.append(f"            7'd{n}: begin cos_coeff = 16'sh{c & 65535:04x}; sin_coeff = 16'sh{s & 65535:04x}; end")
    lines += ["            default: begin cos_coeff = 0; sin_coeff = 0; end", '        endcase', '    end', 'endmodule', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'rtl/coefficient_rom.v')
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    if args.check:
        if args.output.read_text() != render():
            raise SystemExit('FAIL coefficient ROM differs; regenerate it')
        print('PASS coefficient ROM reproducibility')
    else:
        args.output.write_text(render())
